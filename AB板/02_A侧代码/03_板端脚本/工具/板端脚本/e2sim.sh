#!/bin/bash
#======================================================================
# e2sim.sh —— 给 Qoder 用的仿真入口（故意放在纯 ASCII 路径下）
#----------------------------------------------------------------------
# 为什么要有这个包装：
#   Qoder 跑在 Windows 侧（Git Bash），它没有 iverilog；iverilog 装在我们
#   WSL Ubuntu-22.04 里。而仓库路径含中文（GLC-共享包 / E2_FPGA入门练习），
#   把中文路径写在命令行上容易被编码搞坏。
#   所以：**命令行只用 ASCII**，中文路径写在本文件里面。
#
# Qoder 要跑仿真时，只允许执行这一条命令：
#     wsl -d Ubuntu-22.04 -- bash /mnt/e/fudanwei/_logs/sim/e2sim.sh
#
# 退出码：0=全过、2=有 FAIL、3=有编译失败
#======================================================================
exec bash "/mnt/e/fudanwei/GLC-共享包/工具/run_sim.sh"

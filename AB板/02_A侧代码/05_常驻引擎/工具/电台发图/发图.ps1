### C 的实现要点（免得踩坑）

#### ★★ 第 0 条（**最重要，不看这条会白干**）：每个会话的存盘文件名会互相覆盖

`radio_rx_session.py:318` 现在是这一行：

```python
fn = os.path.join(a.dir, 'rx%d.glc' % seq)
```

文件名里**只有会话内的序号 `seq`**，而**每个会话的 `seq` 都从 1 开始**。
改成常驻以后，UI 队列发 10 张 = **10 个 `N=1` 的会话**，每个会话都写 `rx1.glc`
⇒ **前一张被后一张覆盖，收完 10 张磁盘上只剩 1 张**；
而且**日志里 10 行看起来全是成功的**（因为确实每张都收下并 ACK 了）。
**这个坑不看日志能发现，看日志发现不了。**

修法（二选一，**推荐 ①**）：

```python
# ① 每会话一个子目录（推荐：最不容易混，也方便你们按批找）
sdir = os.path.join(a.dir, 's%04d_%s' % (k, time.strftime('%Y%m%d_%H%M%S')))
os.makedirs(sdir, exist_ok=True)
fn = os.path.join(sdir, 'rx%d.glc' % seq)

# ② 文件名带上会话号
fn = os.path.join(a.dir, 'rx_s%04d_%04d.glc' % (k, seq))
```

> 我们这边验收时会**逐个 md5 对文件本体**（不看日志）。
> 你们自己改完也建议这么验一次：**发 3 张、看磁盘上是不是 3 个文件、md5 是不是 3 个不同值**。

#### 其余要点

1. **把 `main()` 里"等 BEGIN + 收 N 帧 + 汇总"整段抽成一个函数**，外层循环调用 ——
   关键是 **`fd` 只开一次、`enter_transparent()` 只做一次**。
   ⚠️ 注意现在有 **4 处 `os.close(fd)`**（`:242` 旧式单帧分支、`:261` ABORT、`:267` 没等到 BEGIN、
   `:330` 会话结束）—— 常驻模式下**这 4 处都不能真的关**，要改成 `return` 出会话函数、
   由外层决定**只有真正要退出进程时才关**。少改一处，下一个会话就收不到帧。
2. **每个会话结束要复位**：`n_expect`、`expected`、`got`、`lens`、`results`、`lens`。
   忘了复位会出现"上一个会话的帧被算进这一个"。
3. **等 BEGIN 时收到"迟到的数据帧"，别按旧式单帧处理**：`:232-244` 那个分支会
   **存文件 + ACK + `return`（结束会话）**，在常驻模式下等于"一个杂散帧就把这一轮废掉"。
   常驻时应把它当**噪声忽略并继续等 BEGIN**（`next_frame` 自带 `MAGIC` 重同步，见 `:144-151`，
   切帧不会因为杂散字节错位）。
4. **会话之间**：`Reader` 的 `buf` 和 `fd` 都保持不动就行，**不要 flush、不要重建**。
   `next_frame` 会自己丢非 `MAGIC` 字节；**要避免的是"完全不读地阻塞等待"** ——
   4.5 s 盲窗就是那个位置来的。
5. **加一个退出条件**，否则进程停不下来：`--max-sessions K`（`K=0` = 永不退出）
   + 收到 `SIGTERM`/`SIGINT` 正常收摊。
6. **`--idle-timeout` 只作用在会话内**；会话之间**不要**用它退出
   （演示时两个会话之间可能隔很久 —— 你们一旦退出，我们下一张就是 `rc=7`，
   要连试 3 次 × 10 s 才失败）。
7. **日志里带上会话序号**（`第 k 个会话，本会话 N 张`），不然出问题分不清是哪一批。
   日志**别覆盖**（现在是 `> log` 还是 `>> log` 检查一下）—— 我们要拿它复盘时会比较有用。


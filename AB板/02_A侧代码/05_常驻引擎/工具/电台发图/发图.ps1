> ⇒ **10 张一次会话 ≈ 5.8 s 空口**（+ 编码 ~1.6 s/张 + 握手 0.44 s）。
> 而且**"一次性写整帧会被电台丢"这个担心在这条链路上没有复现** ——
> 10 帧全第一次成功。（`24` 号文那个坑可能只在特定配置/更长的帧上出现。）

**⇒ 三条结论**

1. **每帧 0.58 s，不是 1.65 s。** 那个 1.65 s 是"200 B/s 应用层节流"拖出来的；
   我们生产链路（`A_send_session.py` 一次性写整帧、不分块）**实测快 2.8 倍**。
2. **`40` 号文"7 张真正空口 4.8 s"（≈0.69 s/张）反而是接近的** ——
   它当年那个数没错，是 `25_GLC容器过空口` 那个 1.65 s 口径不同，把大家带偏了。
3. **不必开 `AT+SYMBOL=6`。** 0.58 s/帧已经够快，开 76.8 kbps 只换来灵敏度/距离的代价。

**每帧用时的经验式**（由上面 3 点拟合，**外推**）：

```
每帧 ≈ 0.30 s（固定开销：ACK 往返/对方处理） + 容器字节 × 1.13 ms
```

⇒ 也就是说 **有效数据速率约 1136 B/s**，含固定开销的 goodput 约 **570 B/s**。
容器越大越划算（固定开销被摊薄）。


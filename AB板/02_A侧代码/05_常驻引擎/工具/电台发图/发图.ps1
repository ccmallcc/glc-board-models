## 二、协议本身**一个字节都没改**（放心）

数据帧格式、`ACK`/`NAK`、控制帧 `0x10~0x13` 全部沿用 `40_电台会话协议_一次监听收N张.md`。
这次改的**只是 A 端"发几张"的组织方式**，不涉及协议。

```
AA 55 | SEQ | LEN(2B 大端) | PAYLOAD | SUM
        SEQ = 0x00 控制帧 ｜ 0x01..0xFE 数据帧（图片序号，从 1 起）
```

| CMD | 名称 | 说明 |
|---|---|---|
| `0x10` | SESSION_BEGIN | `CMD \| N \| MODE \| RATE \| [逐张长度]` |
| `0x11` | SESSION_END | `CMD \| SENT \| OK` |
| `0x12` | SESSION_ABORT | `CMD \| REASON` |
| `0x13` | SESSION_RETRY | `CMD \| K \| seq_1..seq_K` |

应答：`AA 55 06` = ACK，`AA 55 15` = NAK。


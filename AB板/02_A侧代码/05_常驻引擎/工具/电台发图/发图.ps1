**C 的核心就一句话**：把结束条件从"收完这一个会话就退出"改成**"收完回到等下一个 BEGIN"**，
再加一个「收到 K 个会话后退出」的开关（`K=0` = 永不退出）。伪代码：

```python
sessions = 0
while MAX_SESSIONS == 0 or sessions < MAX_SESSIONS:
    pkt = wait_for_begin(timeout=args.timeout)   # 等 SESSION_BEGIN
    if pkt is None:
        break                                    # 超时（暂时没人发了）
    n_expect = pkt.N                             # ★ N 从 BEGIN 读，不是命令行给的
    while True:                                  # 这个会话收完
        ...收帧、回 ACK...
        if got_session_end or got_abort or idle_timeout:
            break
    sessions += 1
    print("[RX] 第 %d 个会话完成（本会话 %d 张）" % (sessions, n_expect))
```

这样**两条路径都兼容**，演示时你们只管把监听挂着，不用掐次数跑。

> ⚠️ `radio_rx_serve.py` 里有一处**故意和 `radio_rx_session.py` 不一样**，别以为是写错了：
> **常驻模式下 `--timeout` 默认是 `0`（一直等）**，因为"没人发"在常驻时是正常态，不该退出。
> 一次性那版留着 180 s 是对的（那时没人发就该退）。

> ⚠️ 另一处故意的：**常驻模式下"等 BEGIN 时收到迟到数据帧"要被当噪声忽略**。
> `radio_rx_session.py:232-244` 那个分支会**存文件 + ACK + 结束会话** ——
> 一次性时那是兼容旧式单帧，常驻时等于"一个杂散帧废掉一轮"。

> 提醒：`40` 号文 §8.2 记过一条 —— **结束判定要用「收到 `SESSION_END`/`ABORT`/空闲超时」，
> 不要用「数够 N 帧」**。否则我们后面发来的**补发帧**（`0x13 SESSION_RETRY`）会被漏掉。

### ★ 三个方案 + 我们改（第四选项）的优缺点对比

先给一条**决定性的量化依据** —— 你们那个脚本**每次启动都要重做一次 AT 握手**：

```python
def enter_transparent(fd):     # radio_rx_session.py:100
    drain(fd, 1.5)             # 1.5 s 什么都不读
    os.write(fd, b'+++')       # 向电台写命令
    r1 = drain(fd, 1.5)        # 1.5 s
    os.write(fd, b'AT+EXIT=1\r\n')
    r2 = drain(fd, 1.5)        # 1.5 s
```

**⇒ 每次启动有 4.5 秒的"盲窗"**（`实测`：`40` 号文 §8.5 记的时序是 t≈3.0 s 才发 `AT+EXIT=1`、t≈4.5 s 才 drain 完）。
这 4.5 s 里**你们根本没在读帧**，而且 `drain` 会把**已经到达的数据直接丢掉**；
同时还在往电台写 `+++` —— 如果我们那边正在发，可能互相干扰。

| | **A 循环跑 N 次** | **B 一次收完** | **C 改成常驻** | **D 我们改成一次会话发 N 张** |
|---|---|---|---|---|
| 谁要改 | 都不用 | 都不用 | **你们**（~20 行） | **我们**（要动 `ui_send.sh`） |
| 兼容 **UI 队列** | ✅ | ❌ **只收到第一张** | ✅ | ✅ |
| 兼容 **命令行** | ⚠️ 第 1 轮就收完，后面 N−1 轮**空等到超时** | ✅ | ✅ | ✅ |
| **会话间盲窗** | ❌ **每张一次 4.5 s，且会丢帧** | 无（单会话） | ✅ **无**（进程不退、串口不关、不重握手） | 无（单会话） |
| 要事先知道张数 | ❌ 要（否则白等到 `-t`） | ✅ 不用 | ✅ 不用 | ✅ 不用 |
| 演示时怎么用 | 掐着数跑 | 不适用 | **挂上不用管** | 挂上不用管 |
| 我们失败停队时 | 剩余轮次白等 | 不适用 | 继续挂着（或按 K 退出） | 不适用 |
| 我们的额外代价 | — | — | — | **第一张出去更晚**：要先把 N 张全编完（N × ~1.6 s）才开始会话 |

**结论（我们的看法）**：


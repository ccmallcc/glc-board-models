（`n_expect, mode, rate, lens = parse_begin(payload)`）。

> ⇒ **一次运行 = 一个会话。** 这是理解下面三个选项的前提。

### 选项 A（零改动，但**有代价**）：**循环收**

```bash
# A 端从 UI 队列发 5 张 = 5 个独立会话 ⇒ 循环跑 5 次
for i in $(seq 1 5); do
    python3 /root/radio_rx_session.py -d /root/glc/pack/rxs

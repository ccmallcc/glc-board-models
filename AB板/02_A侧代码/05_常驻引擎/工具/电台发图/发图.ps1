## 四、我们这边的时序与退出码（方便你们判断）

### 单个会话（UI 队列走的就是这个）

```
A 端                                        B 端
 │                                           │
 ├── SESSION_BEGIN (N=1) ──────────────────►│  进入会话模式
 │◄───────────── ACK ───────────────────────┤
 ├── 数据帧 seq=1 (300~344 B) ─────────────►│  存 rx1.glc
 │◄───────────── ACK ───────────────────────┤
 ├── SESSION_END (sent=1, ok=1) ───────────►│  汇总
 │◄───────────── ACK ───────────────────────┤
```

**每张给你们的等待窗口是 30 秒**：`--begin-attempts 3`，每次「等 6 s + 隔 4 s」= 10 s。
（默认是 99 次；UI 特意压到 3 次，因为在触摸屏上干等 50 s 体验太差。
实测你们在场时**每次第 1 次就答**，约 0.22 s。）

### 我们的退出码（`A_send_session.py`）

| rc | 含义 | 你们那边通常是什么情况 |
|---|---|---|
| 0 | 全部确认 | 正常 |
| 1 | 有缺帧 | 个别帧没收到 |
| 2 | 找不到电台设备 | （我们自己的问题） |

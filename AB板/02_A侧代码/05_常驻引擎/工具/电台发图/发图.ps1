#### ★ 9.3.1 C 和 D 差的那 4 s 到底在哪（10 张，逐项拆开）

把两边的账**逐项对齐**，差距就只剩一处：

| 项 | 次数（C / D） | **C 常驻** | **D 我们改** |
|---|---|---|---|
| 编码（NPU） | 10 / 10 | 10 × 1.4 = **14.0 s** | 10 × 1.4 = **14.0 s** |
| 数据帧 + ACK | 10 / 10 | 10 × 0.58 = **5.8 s** | 10 × 0.58 = **5.8 s** |
| **SESSION_BEGIN** | **10 / 1** | **2.2 s** | **0.22 s** |
| **SESSION_END** | **10 / 1** | **2.2 s** | **0.22 s** |
| **合计** | | **≈24.2 s** | **≈20.2 s** |

> **⇒ 差距 100% 来自「握手次数」，一行公式：`Δ = (0.22 + 0.22) × (N − 1) = 0.44 × (N − 1)` 秒。**
> N=1 时两边**完全一样**；N=3 → 0.88 s；N=10 → 3.96 s。
> **相对差距有上限**：`Δ / C = 0.44(N−1) / (2.42N)`，N→∞ 也只有 **18%**。
> 因为时间的大头（编码 58% + 射频帧 24%）**两边逐字相同**，谁都动不了。

**但 D 的这 4 s 不是白拿的** —— 按现在的实现，代价压在**首张出图时刻**上：

| 时刻（10 张，暖机） | C 常驻 | D 我们改 |
|---|---|---|
| B 端看到**第 1 张** | **≈2.2 s**（编码 1.4 + BEGIN 0.22 + 帧 0.58） | **≈14.8 s**（要先编完 10 张） |
| 全部发完 | ≈24.2 s | ≈20.2 s |

> ⇒ **省 4 s，把首张推迟 12.6 s。** 演示时"按下发送多久有反应"比"总耗时"重要得多。

#### ★★ 9.3.2 这个"首张晚"**不是 D 的必然代价**（选型时最该看的一条）

D 之所以首张晚，**只是因为 `send_image.sh` 是"先编完 N 张、再开会话"**
（编码在 `150~290` 行，`344` 行才调 `A_send_session.py`）—— **不是协议限制**。

协议侧**早就留好了口子**，`A_send_session.py:182` 原话：

> `--no-lens`　BEGIN 里不列逐张长度（B 就不做长度校验；**允许边编码边发**）

而 `send_image.sh:32-36` **已经把 `--no-lens` 原样转发**给 `A_send_session.py`。

⇒ 把 D 的实现改成「**同一个会话内，编一张、发一张、再编下一张**」，就是：

```
BEGIN(0.22) → [ 编码 1.4 → 发 0.58 ] × 10 → END(0.22)   =  ≈20.2 s
首张出图 = 0.22 + 1.4 + 0.58                            =  ≈2.2 s
```

**总耗时和首张时刻同时拿到 D 和 C 各自的长处** —— 因为编码和射频帧本来就得串行，
"先编完"和"边编边发"的总时间**是同一个数**：`10 × (1.4 + 0.58) + 0.44`。

> ⚠️ 这条是**外推**（按时序相加），**我们还没实现**。要动的只有 `send_image.sh`；
> `ui_send.sh` 那套自愈逻辑（WARM ctime 标记 / rc3,6 清标记 / rc7 连续 2 次清标记）**可以原样保留**。

> 再上一层的天花板（**同样是外推，未做**）：编码（NPU）和发送（串口）用的是**不同设备**，
> 开两条就能重叠 ⇒ `总 ≈ max(10×1.4, 0.44 + 10×0.58) ≈ 14 s`，首张仍 ≈2.2 s。
> 但这是进程/线程改造，**不划算**，列在这里只是让你们知道还剩多少余量。

> 📌 **口径注**：本节按 `1.4 s/张` 算编码（`send_image.sh:24` 与板端 UI 日志"累计已用 1 s"一致）；
> 上面 §9.3 表里写的是 `1.6 s/张`（取自 `45`/`53` 号文）。两者差 0.2 s/张，
> **只影响两列的绝对值，不影响差值**（差值只由握手次数决定）。

### 9.4 我们做了什么：`速率基准.sh`

```
工具/无线/速率基准.sh          在板子上跑，发 N 张并出报告
工具/无线/速率基准_解析.py     解析 A_send_session 日志（可单独喂日志验证）
```

它把每帧的 ACK 用时、第几次成功、丢帧次数、goodput 都列出来，并自动给
「要不要开 SYMBOL=6」的建议。**以后怀疑链路变慢，跑一次就知道。**

⚠️ 写这个脚本时我们自己踩了一个坑，记在这里（你们写解析时也会遇到）：
**日志里会出现"续行"** —— AT 应答里嵌了换行，把 `[OK]` 顶到下一行，
于是 `AT+FREQ?` / `AT+SYMBOL?` 两行**被静默丢掉**（只有 `AT+UART?` 解析出来）。
修法是解析前先"把不以 `[SS]` 开头的行并回上一行"。

